"""Bakes Data/Affixes.lua: every Mythic+ affix (ID, name, description) listed on Wowhead's affix page.
Run it again after a patch:  python tools/bake_affixes.py   (then /reload the game)."""
import json
import os
import re
import urllib.request

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "Data", "Affixes.lua")


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    req = urllib.request.Request("https://www.wowhead.com/affixes", headers={"User-Agent": "Mozilla/5.0"})
    page = urllib.request.urlopen(req, timeout=60).read().decode("utf-8", "replace")
    found = {}
    for m in re.finditer(r'\{"description":"((?:[^"\\]|\\.)*)","id":(\d+),"name":"((?:[^"\\]|\\.)*)"', page):
        desc = json.loads('"' + m.group(1) + '"')
        name = json.loads('"' + m.group(3) + '"')
        found[int(m.group(2))] = (name, desc)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("-- SeviathsUsefulTools - Mythic+ affixes (generated by tools/bake_affixes.py from the Wowhead affix page)\n\n")
        f.write("local _, SFP = ...\n\nSFP.Affixes = {\n")
        for i in sorted(found):
            f.write("    [%d] = { %s, %s },\n" % (i, lua_str(found[i][0]), lua_str(found[i][1])))
        f.write("}\n")
    print("wrote", len(found), "affixes")


if __name__ == "__main__":
    main()
