"""Bakes auction prices from the official Blizzard API, without playing: the region-wide commodity prices of every region and the
listings of the biggest connected realms. The files go to collected/ like the prices of your own scans.

Needs the free API client of https://develop.battle.net/access/clients (see tools/bake_connected_realms.py for where to put it).

    python tools/bake_prices_api.py                 commodities of us, eu, kr, tw + the realms named in BIG_REALMS
    python tools/bake_prices_api.py --regions us    only one region

Commodities (materials, consumables, reagents) are one price list for the whole region, so the file "gold.REGION_US.lua" covers every
US realm for them. The addon uses a realm's own file first, then its region's commodity file.
"""
import json
import os
import re
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import bake_connected_realms as conn   # noqa: E402

OUT = os.path.join(HERE, "..", "collected")
REGIONS = ["us", "eu", "kr", "tw"]
MAX_COPPER = 1_000_000 * 10000   # a joke listing, not a value
BATCH = 20000
# the realms whose own listings (gear and other single items) are baked, by name (spaces removed); the others use the commodities
BIG_REALMS = {
    "us": ["Area52", "Stormrage", "Illidan", "Tichondrius", "Sargeras", "Proudmoore", "Mal'Ganis", "Thrall", "Barthilas", "Zul'jin"],
    "eu": ["Draenor", "Tarren Mill", "Silvermoon", "Kazzak", "Stormscale", "Twisting Nether", "Ravencrest", "Argent Dawn", "Hyjal", "Sylvanas"],
}


def get(path, region, tok):
    return conn.get_json("https://%s.api.blizzard.com%s" % (region, path), headers={"Authorization": "Bearer " + tok})


def write(key, region, items):
    """items: {itemID: copper}; same file format as bake_gold.py."""
    items = {k: v for k, v in items.items() if 0 < v < MAX_COPPER}
    if not items:
        return
    now = int(time.time())
    name = re.sub(r"[^A-Za-z0-9]+", "_", key).strip("_")
    path = os.path.join(OUT, "gold.%s.lua" % name)
    ids = sorted(items)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("-- generated by tools/bake_prices_api.py: auction prices of %s from the Blizzard API\n" % key)
        fh.write("SeviathsUsefulToolsGold = SeviathsUsefulToolsGold or {}\n")
        fh.write('local R = { t = %d, n = %d, s = {} }\nSeviathsUsefulToolsGold["%s"] = R\n' % (now, len(ids), key))
        for i in range(0, len(ids), BATCH):
            chunk = "".join("%d,%d;" % (n, items[n]) for n in ids[i:i + BATCH])
            fh.write(';R.s[#R.s+1]="%s"\n' % chunk)
    print("%s: %d prices" % (key, len(items)))


def cheapest(auctions, unit_key):
    best = {}
    for a in auctions:
        item = (a.get("item") or {}).get("id")
        price = a.get(unit_key) or a.get("buyout") or 0
        if item and price and (item not in best or price < best[item]):
            best[item] = price
    return best


def main():
    cid, secret = conn.credentials()
    if not (cid and secret):
        sys.exit("No Blizzard API client found. See tools/bake_connected_realms.py.")
    tok = conn.token(cid, secret)
    regions = REGIONS
    if "--regions" in sys.argv:
        regions = sys.argv[sys.argv.index("--regions") + 1].split(",")
    os.makedirs(OUT, exist_ok=True)
    for region in regions:
        ns = "?namespace=dynamic-%s&locale=en_US" % region
        d = get("/data/wow/auctions/commodities" + ns, region, tok)
        write("REGION_" + region.upper(), region, cheapest(d.get("auctions", []), "unit_price"))
        wanted = {re.sub(r"[\s'-]", "", n) for n in BIG_REALMS.get(region, [])}
        if not wanted:
            continue
        index = get("/data/wow/connected-realm/index" + ns, region, tok)
        for entry in index.get("connected_realms", []):
            cr = conn.get_json(entry["href"].split("?")[0] + ns.replace("?", "?"), headers={"Authorization": "Bearer " + tok})
            names = sorted(re.sub(r"\s", "", r.get("name") or "") for r in cr.get("realms", []))
            if not wanted & {re.sub(r"[\s'-]", "", n) for n in names}:
                continue
            a = get("/data/wow/connected-realm/%d/auctions%s" % (cr["id"], ns), region, tok)
            write(",".join(names), region, cheapest(a.get("auctions", []), "buyout"))
            time.sleep(0.5)


if __name__ == "__main__":
    main()
