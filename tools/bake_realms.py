"""Bakes Data/Realms.lua: the realm names of the game, read from the installed Raider.IO addon (RaiderIO/db/db_realms.lua).

A listed player usually has no realm in the name the game gives. The addon then searches every realm for the name; this is its list of
realms. Run it again after Raider.IO updates:   python tools/bake_realms.py   (then /reload the game)
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ADDONS = os.path.abspath(os.path.join(HERE, "..", ".."))
SRC = os.path.join(ADDONS, "RaiderIO", "db", "db_realms.lua")
OUT = os.path.join(HERE, "..", "Data", "Realms.lua")


def main():
    if not os.path.exists(SRC):
        raise SystemExit("The Raider.IO addon is not installed next to this one: " + SRC)
    text = open(SRC, encoding="utf-8", errors="replace").read()
    by_slug = {}
    for name, slug in re.findall(r'\["([^"]+)"\]\s*=\s*"([^"]+)"', text):
        by_slug.setdefault(slug, name)   # two spellings of one realm: the first
    names = sorted(by_slug.values())
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("-- SeviathsUsefulTools - realm names (generated by tools/bake_realms.py from the installed Raider.IO addon)\n\n")
        f.write("local _, SFP = ...\n\nSFP.Realms = {\n")
        for n in names:
            f.write('    "%s",\n' % n.replace("\\", "\\\\").replace('"', '\\"'))
        f.write("}\n")
    print("wrote", len(names), "realms to", OUT)


if __name__ == "__main__":
    main()
