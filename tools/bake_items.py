"""Bakes the items of Wowhead's lists that are not transmog (materials, consumables, containers, quest items ...) into small load-on-demand addon folders.

Source: tools/items_sources.txt (id|name|quality|source types|sourcemore|item class|subclass|slot|level|required level|list), minus the items of
tools/transmog_items.txt (those are in the Transmog folders).
Output: SeviathsUsefulTools_Items1, 2 ... each an Items.lua filling SeviathsItemBlocks[id // 500] = "id|name|quality|item class|subclass|level|required level|list\n..." and
Data/ItemIndex.lua in the main addon (which folder holds which blocks). The Codex reads them when the Loot & Items section is open.
Run: python tools/bake_items.py   (update_data.py runs it)
"""
import os
import shutil

HERE = os.path.dirname(os.path.abspath(__file__))
ADDON = os.path.dirname(HERE)
ADDONS = os.path.dirname(ADDON)
BLOCK = 500
MAX_FILE = 200_000
BS = chr(92)
NL = BS + "n"

tm = set()
tp = os.path.join(HERE, "transmog_items.txt")
if os.path.exists(tp):
    for line in open(tp, encoding="utf8").read().splitlines():
        p = line.split("|")
        if p and p[0].isdigit():
            tm.add(int(p[0]))

blocks = {}
n = 0
for line in open(os.path.join(HERE, "items_sources.txt"), encoding="utf8").read().splitlines():
    p = line.split("|")
    if len(p) < 11 or not p[0].isdigit() or int(p[0]) in tm:
        continue
    name = p[1].replace(BS, "").replace('"', "'")
    rec = "|".join([p[0], name, p[2], p[5], p[6], p[8], p[9], p[10]])
    blocks.setdefault(int(p[0]) // BLOCK, []).append(rec)
    n += 1

for old in os.listdir(ADDONS):
    if old.startswith("SeviathsUsefulTools_Items"):
        shutil.rmtree(os.path.join(ADDONS, old))
parts, cur, size = [], [], 0
for b in sorted(blocks):
    line = 'B[%d]="%s"' % (b, NL.join(blocks[b]))
    if cur and size + len(line) > MAX_FILE:
        parts.append(cur)
        cur, size = [], 0
    cur.append((b, line))
    size += len(line) + 1
if cur:
    parts.append(cur)
main_toc = open(os.path.join(ADDON, "SeviathsUsefulTools.toc"), encoding="utf8").read().splitlines()
interface = next((l for l in main_toc if l.startswith("## Interface")), "## Interface: 120100")
index = []
for i, part in enumerate(parts, 1):
    folder = "SeviathsUsefulTools_Items%d" % i
    d = os.path.join(ADDONS, folder)
    os.makedirs(d)
    with open(os.path.join(d, "Items.lua"), "w", encoding="utf8", newline="\n") as f:
        f.write("-- generated by tools/bake_items.py: items of Wowhead's lists, part %d of %d (%d items in all)\n" % (i, len(parts), n))
        f.write("SeviathsItemBlocks = SeviathsItemBlocks or {}\nlocal B = SeviathsItemBlocks\n")
        for _, line in part:
            f.write(line + "\n")
    with open(os.path.join(d, folder + ".toc"), "w", encoding="utf8", newline="\n") as f:
        f.write(interface + "\n## Title: SeviathsUsefulTools - items %d\n" % i)
        f.write("## Notes: Names and types of items, read only when the Codex lists them.\n")
        f.write("## Dependencies: SeviathsUsefulTools\n## LoadOnDemand: 1\n## Author: Seviath\n\nItems.lua\n")
    index.append('    { %d, %d, "%s" },' % (part[0][0], part[-1][0], folder))
with open(os.path.join(ADDON, "Data", "ItemIndex.lua"), "w", encoding="utf8", newline="\n") as f:
    f.write("-- generated by tools/bake_items.py: which load-on-demand folder holds which blocks of 500 item ids\n\nlocal _, SFP = ...\n\n")
    f.write("SFP.ItemParts = {\n" + "\n".join(index) + "\n}\n")
print("%d items in %d folders" % (n, len(parts)))
