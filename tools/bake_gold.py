"""Bakes the auction prices of every realm you scanned into collected/gold.<Realm>.lua, so a player who installs the addon has gold
values for items even before his own scan (prices of other servers are usually close). Called by tools/update_data.py.

Per realm group (the key the addon uses: connected realms written together, e.g. "ArgentDawn" or "Kazzak,Ravencrest"): { t = newest
price time, p = { [itemID] = copper } }. A price you scanned later replaces an older baked one; prices only the older bake had stay.
In the game a player's own scan always wins unless the shipped price is newer than his.
"""
import glob
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.setrecursionlimit(30000)
from luadata import P, parse_file   # noqa: E402

OUT = os.path.join(HERE, "..", "collected")
RETAIL = os.path.abspath(os.path.join(HERE, "..", "..", "..", ".."))
BATCH = 20000   # prices per generated function
MAX_COPPER = 1_000_000 * 10000   # a listing of a million gold or more is a joke price (9,999,999 g is the limit), not a value: left out


def read_old(path):
    """{item: (copper, time)} and t of an earlier baked file."""
    out = {}
    if not os.path.exists(path):
        return out
    text = open(path, encoding="utf-8").read()
    p = P(text)
    mt = re.search(r"R = \{ t = (\d+)", text)
    file_t = int(mt.group(1)) if mt else 0
    # the newer format: long strings "id,price;id,price;..."
    for m in re.finditer(r'^;?R\.s\[#R\.s\+1\]="([^"]*)"', text, re.M):
        for k, v in re.findall(r"(\d+),(\d+);", m.group(1)):
            out[int(k)] = (int(v), file_t)
    for m in re.finditer(r'^;\(function\(\) addP\("[^"]*",', text, re.M):
        v, _ = p.value(m.end())
        for item, rec in v.items():
            # older files kept { copper, time } per item; now one number per item and one time per file (less memory in the game)
            out[item] = tuple(rec) if isinstance(rec, list) else (rec, file_t)
    return out


def safe_name(key):
    return re.sub(r"[^A-Za-z0-9]+", "_", key).strip("_")


def main():
    files = glob.glob(os.path.join(RETAIL, "WTF", "Account", "*", "SavedVariables", "SeviathsUsefulTools.lua"))
    if not files:
        sys.exit("no saved data found")
    found = {}
    for f in files:
        db = parse_file(f).get("SeviathsUsefulToolsDB") or {}
        # the whole-auction-house prices of the last scan (fast scan or all sections): every item seen, cheapest price
        scanned = db.get("realmScan") or {}
        for key, items in (db.get("ahAll") or {}).items():
            if isinstance(items, dict):
                cur = found.setdefault(key, {})
                t = scanned.get(key) or 0
                for item, price in items.items():
                    if isinstance(price, (int, float)) and price > 0 and (item not in cur or cur[item][1] < t):
                        cur[item] = (int(price), t)
        for key, items in (db.get("realmPrices") or {}).items():
            if not isinstance(items, dict):
                continue
            cur = found.setdefault(key, {})
            for item, rec in items.items():
                if isinstance(rec, dict) and rec.get("p") and not rec.get("ext"):   # own scan only, not copied from other addons
                    t = rec.get("t") or 0
                    if item not in cur or cur[item][1] < t:
                        cur[item] = (rec["p"], t)
    # earlier bakes first (a newer scan replaces an older price), then the filters below see everything
    for key, items in found.items():
        old = read_old(os.path.join(OUT, "gold.%s.lua" % safe_name(key)))
        for item, (p, t) in old.items():
            if item not in items or items[item][1] < t:
                items[item] = (p, t)
    # a price far above what the other realms show for the same item is a troll listing (some servers have many): left out
    dropped = 0
    for key, items in found.items():
        for item, (p, t) in list(items.items()):
            others = sorted(o[item][0] for k, o in found.items() if k != key and item in o)
            if others and p > 8 * others[len(others) // 2] and p > 1000 * 10000:
                del items[item]
                dropped += 1
    print("dropped %d prices far above the other realms" % dropped)
    os.makedirs(OUT, exist_ok=True)
    for key, items in found.items():
        if not items:
            continue
        path = os.path.join(OUT, "gold.%s.lua" % safe_name(key))
        items = {k: v for k, v in items.items() if v[0] < MAX_COPPER}
        newest = max(t for _, t in items.values())
        ids = sorted(items)
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write("-- generated by tools/bake_gold.py: auction prices of realm group %s, scanned in the game\n" % key)
            fh.write("SeviathsUsefulToolsGold = SeviathsUsefulToolsGold or {}\n")
            # the prices are a few long texts, turned into a table only for the realm the player is on (a text is one constant)
            fh.write('local R = { t = %d, n = %d, s = {} }\nSeviathsUsefulToolsGold["%s"] = R\n' % (newest, len(ids), key))
            for i in range(0, len(ids), BATCH):
                chunk = "".join("%d,%d;" % (n, items[n][0]) for n in ids[i:i + BATCH])
                fh.write(';R.s[#R.s+1]="%s"\n' % chunk)
        print("gold %s: %d prices" % (key, len(items)))


if __name__ == "__main__":
    main()
