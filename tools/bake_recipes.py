"""Bakes Data/RecipeData.lua: every crafting recipe (name, output item, reagents) of the nine crafting professions.

Recipe names and reagent lists are game facts. They are read from Wowhead's public profession pages
(one request every few seconds) and written as plain data. Run it again after a game patch:

    python tools/bake_recipes.py

The planner uses this data for professions you never opened in the game; recipes your characters learned
themselves (saved in the addon's data) take precedence.
"""
import json
import os
import re
import sys
import time
import urllib.request

PROFS = [
    ("Alchemy", "alchemy"), ("Blacksmithing", "blacksmithing"), ("Cooking", "cooking"),
    ("Enchanting", "enchanting"), ("Engineering", "engineering"), ("Inscription", "inscription"),
    ("Jewelcrafting", "jewelcrafting"), ("Leatherworking", "leatherworking"), ("Tailoring", "tailoring"),
]

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "Data", "RecipeData.lua")


def fetch(slug):
    req = urllib.request.Request(
        "https://www.wowhead.com/spells/professions/" + slug,
        headers={"User-Agent": "Mozilla/5.0"},
    )
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read().decode("utf-8", "replace")


def parse(html):
    """The page holds a JavaScript array, not strict JSON: cut it into objects and read the few fields needed."""
    i = html.find("var listviewspells = [")
    if i < 0:
        return []
    j = html.find("];", i)
    body = html[i + len("var listviewspells = "): j + 1]
    out = []
    for chunk in body.split('},{"cat"')[0:]:
        m_id = re.search(r'"id":(\d+)', chunk)
        m_name = re.search(r',"name":"((?:[^"\\]|\\.)*)"', chunk)
        m_creates = re.search(r'"creates":\[(\d+)', chunk)
        m_reag = re.search(r'"reagents":(\[\[[\d,\[\]]*\]\])', chunk)
        if not (m_id and m_name and m_reag):
            continue
        name = json.loads('"' + m_name.group(1) + '"')
        out.append({
            "id": int(m_id.group(1)), "name": name,
            "creates": [int(m_creates.group(1))] if m_creates else [],
            "reagents": json.loads(m_reag.group(1)),
        })
    return out

def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    rows = []
    for name, slug in PROFS:
        print("reading", name, file=sys.stderr)
        data = parse(fetch(slug))
        n = 0
        for d in sorted(data, key=lambda x: x.get("name", "")):
            reagents = d.get("reagents") or []
            creates = d.get("creates") or []
            if not reagents or not d.get("name"):
                continue
            out = creates[0] if creates else 0
            rg = ",".join("{%d,%d}" % (r[0], r[1]) for r in reagents)
            rows.append("{%d,%s,%s,%d,{%s}}," % (d["id"], lua_str(name), lua_str(d["name"]), out, rg))
            n += 1
        print("  ", n, "recipes", file=sys.stderr)
        time.sleep(3)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("-- SeviathsUsefulTools - crafting recipes of the nine crafting professions (generated by tools/bake_recipes.py)\n")
        f.write("-- Names and reagents are game facts read from Wowhead's public profession pages.\n")
        f.write("-- Row: { spellID, profession, recipe name, crafted item ID (0 = none), { {reagent item ID, amount}, ... } }\n\n")
        f.write("local _, SFP = ...\n\nSFP.RecipeData = {\n")
        for r in rows:
            f.write(r + "\n")
        f.write("}\n")
    print("wrote", len(rows), "recipes to", OUT, file=sys.stderr)


if __name__ == "__main__":
    main()
