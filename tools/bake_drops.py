"""Bakes the items Wowhead lists as dropped by a monster into small load-on-demand addon folders (SeviathsUsefulTools_Drops1, 2 ...).

Source: tools/items_sources.txt, lines id|name|quality|source types|sourcemore|item class|subclass|slot|level|required level|list
  sourcemore = "type:id:zone:name:difficulty:boss flag" parts joined by ";" - type 1 is a monster (id = the monster's id)
  (read in a browser from Wowhead's item lists: /classic/items, /items?filter=166;6;0 (Draenor), 166;12;0 (Midnight), /transmog-items)
Output: Drops folders, each a Drops.lua filling SeviathsDropBlocks[npcID // 500] = "npcID|itemID,itemID,...\n..." and Data/DropIndex.lua in the main addon
(which folder holds which blocks). The game loads only the folder of the monster it looks at (hover on the map, a rare, a boss).
Run: python tools/bake_drops.py   (update_data.py runs it)
"""
import os
import shutil

HERE = os.path.dirname(os.path.abspath(__file__))
ADDON = os.path.dirname(HERE)
ADDONS = os.path.dirname(ADDON)
BLOCK = 500
MAX_FILE = 400_000
BS = chr(92)
NL = BS + "n"

npc_items = {}
n_items = 0
src = os.path.join(HERE, "items_sources.txt")
for line in open(src, encoding="utf8").read().splitlines():
    p = line.split("|")
    if len(p) < 5 or not p[0].isdigit():
        continue
    sources = p[3].split(",")
    if "2" not in sources:
        continue
    n_items += 1
    for part in p[4].split(";"):
        f = part.split(":")
        if len(f) >= 2 and f[0] == "1" and f[1].isdigit():
            npc_items.setdefault(int(f[1]), set()).add(int(p[0]))

blocks = {}
for npc, items in npc_items.items():
    blocks.setdefault(npc // BLOCK, []).append("%d|%s" % (npc, ",".join(str(i) for i in sorted(items))))

for old in os.listdir(ADDONS):
    if old.startswith("SeviathsUsefulTools_Drops"):
        shutil.rmtree(os.path.join(ADDONS, old))
parts, cur, size = [], [], 0
for b in sorted(blocks):
    line = 'B[%d]="%s"' % (b, NL.join(sorted(blocks[b])))
    if cur and size + len(line) > MAX_FILE:
        parts.append(cur)
        cur, size = [], 0
    cur.append((b, line))
    size += len(line) + 1
if cur:
    parts.append(cur)
main_toc = open(os.path.join(ADDON, "SeviathsUsefulTools.toc"), encoding="utf8").read().splitlines()
interface = next((l for l in main_toc if l.startswith("## Interface")), "## Interface: 120100")
index = []
for i, part in enumerate(parts, 1):
    folder = "SeviathsUsefulTools_Drops%d" % i
    d = os.path.join(ADDONS, folder)
    os.makedirs(d)
    with open(os.path.join(d, "Drops.lua"), "w", encoding="utf8", newline="\n") as f:
        f.write("-- generated by tools/bake_drops.py: items Wowhead lists as dropped by a monster, part %d of %d\n" % (i, len(parts)))
        f.write("SeviathsDropBlocks = SeviathsDropBlocks or {}\nlocal B = SeviathsDropBlocks\n")
        for _, line in part:
            f.write(line + "\n")
    with open(os.path.join(d, folder + ".toc"), "w", encoding="utf8", newline="\n") as f:
        f.write(interface + "\n## Title: SeviathsUsefulTools - monster drops %d\n" % i)
        f.write("## Notes: Items monsters drop, read only when a monster of this part is looked at.\n")
        f.write("## Dependencies: SeviathsUsefulTools\n## LoadOnDemand: 1\n## Author: Seviath\n\nDrops.lua\n")
    index.append('    { %d, %d, "%s" },' % (part[0][0], part[-1][0], folder))
with open(os.path.join(ADDON, "Data", "DropIndex.lua"), "w", encoding="utf8", newline="\n") as f:
    f.write("-- generated by tools/bake_drops.py: which load-on-demand folder holds the drops of which monsters (blocks of 500 monster ids)\n\nlocal _, SFP = ...\n\n")
    f.write("SFP.DropParts = {\n" + "\n".join(index) + "\n}\n")
print("%d monsters with drops (from %d dropped items), %d folders" % (len(npc_items), n_items, len(parts)))
