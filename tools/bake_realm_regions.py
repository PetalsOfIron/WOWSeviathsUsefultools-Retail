"""Bakes Data/RealmRegions.lua: which region (us / eu) each realm is in, read from the installed Raider.IO addon.

Raider.IO keeps its character data per region (db/db_mythicplus_us_characters.lua, db_mythicplus_eu_characters.lua ...), as provider.db["Realm"] = {...}: the realm
names in each file are the realms of that region. A realm in both is saved as "both".
Output: SFP.RealmRegion["RealmName"] = "us" | "eu" | "both"   (the Guild Directory has US and EU buttons that use it)
Run: python tools/bake_realm_regions.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ADDONS = os.path.abspath(os.path.join(HERE, "..", ".."))
DB = os.path.join(ADDONS, "RaiderIO", "db")
OUT = os.path.join(HERE, "..", "Data", "RealmRegions.lua")
PATTERN = re.compile(r'provider\.db\["([^"]+)"\]=')

regions = {}
for region in ("us", "eu"):
    names = set()
    for kind in ("mythicplus", "raiding"):
        path = os.path.join(DB, "db_%s_%s_characters.lua" % (kind, region))
        if not os.path.exists(path):
            continue
        with open(path, encoding="utf-8", errors="replace") as f:
            for line in f:
                for m in PATTERN.finditer(line):
                    names.add(m.group(1))
    regions[region] = names
if not regions["us"] and not regions["eu"]:
    raise SystemExit("The Raider.IO addon is not installed next to this one: " + DB)

out = {}
for r in sorted(regions["us"] | regions["eu"]):
    in_us, in_eu = r in regions["us"], r in regions["eu"]
    out[r] = "both" if (in_us and in_eu) else ("us" if in_us else "eu")
with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("-- SeviathsUsefulTools - the region of each realm (generated by tools/bake_realm_regions.py from the installed Raider.IO addon)\n\n")
    f.write("local _, SFP = ...\n\nSFP.RealmRegion = {\n")
    for r, v in out.items():
        f.write('    ["%s"] = "%s",\n' % (r.replace("\\", "\\\\").replace('"', '\\"'), v))
    f.write("}\n")
print("%d realms (%d us, %d eu, %d both)" % (len(out), sum(1 for v in out.values() if v == "us"), sum(1 for v in out.values() if v == "eu"), sum(1 for v in out.values() if v == "both")))
