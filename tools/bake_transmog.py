"""Bakes the transmog items of Wowhead's list (tools/transmog_items.txt) into small load-on-demand addon folders.

Source lines: id|name|quality|source type|source name|class|subclass|slot|level|required level|classes  (read in a browser from https://www.wowhead.com/transmog-items)
Output: SeviathsUsefulTools_Transmog1, 2 ... next to the main addon (each about 600 KB, one Transmog.lua) filling
SeviathsTransmogBlocks[id // 500] = "id|name|quality|source|source name|item class|subclass|slot|required level|classes\n..."
and Data/TransmogIndex.lua in the main addon: which folder holds which blocks. The game loads only the folder of the item it looks at.
Run: python tools/bake_transmog.py   (update_data.py runs it)
"""
import os
import shutil

HERE = os.path.dirname(os.path.abspath(__file__))
ADDON = os.path.dirname(HERE)
ADDONS = os.path.dirname(ADDON)
BLOCK = 500
MAX_FILE = 600_000
BS = chr(92)
NL = BS + "n"

blocks = {}
for line in open(os.path.join(HERE, "transmog_items.txt"), encoding="utf8").read().splitlines():
    p = line.split("|")
    if len(p) < 5 or not p[0].isdigit():
        continue
    iid = int(p[0])
    p += [""] * (11 - len(p))
    rec = "|".join([p[0], p[1].replace(BS, "").replace('"', "'"), p[2], p[3], p[4].replace(BS, "").replace('"', "'"), p[5], p[6], p[7], p[9], p[10]])
    blocks.setdefault(iid // BLOCK, []).append(rec)

for old in os.listdir(ADDONS):
    if old.startswith("SeviathsUsefulTools_Transmog"):
        shutil.rmtree(os.path.join(ADDONS, old))
parts, cur, size = [], [], 0
for b in sorted(blocks):
    line = 'B[%d]="%s"' % (b, NL.join(blocks[b]))
    if cur and size + len(line) > MAX_FILE:
        parts.append(cur)
        cur, size = [], 0
    cur.append((b, line))
    size += len(line) + 1
if cur:
    parts.append(cur)
total = sum(len(v) for v in blocks.values())
main_toc = open(os.path.join(ADDON, "SeviathsUsefulTools.toc"), encoding="utf8").read().splitlines()
interface = next((l for l in main_toc if l.startswith("## Interface")), "## Interface: 120100")
index = []
for i, part in enumerate(parts, 1):
    folder = "SeviathsUsefulTools_Transmog%d" % i
    d = os.path.join(ADDONS, folder)
    os.makedirs(d)
    with open(os.path.join(d, "Transmog.lua"), "w", encoding="utf8", newline="\n") as f:
        f.write("-- generated by tools/bake_transmog.py: Wowhead's transmog items, part %d of %d (%d items in all)\n" % (i, len(parts), total))
        f.write("SeviathsTransmogBlocks = SeviathsTransmogBlocks or {}\nlocal B = SeviathsTransmogBlocks\n")
        for _, line in part:
            f.write(line + "\n")
    with open(os.path.join(d, folder + ".toc"), "w", encoding="utf8", newline="\n") as f:
        f.write(interface + "\n## Title: SeviathsUsefulTools - transmog items %d\n" % i)
        f.write("## Notes: Where transmog items come from, read only when an item of this part is looked at.\n")
        f.write("## Dependencies: SeviathsUsefulTools\n## LoadOnDemand: 1\n## Author: Seviath\n\nTransmog.lua\n")
    index.append('    { %d, %d, "%s" },' % (part[0][0], part[-1][0], folder))
with open(os.path.join(ADDON, "Data", "TransmogIndex.lua"), "w", encoding="utf8", newline="\n") as f:
    f.write("-- generated by tools/bake_transmog.py: which load-on-demand folder holds which blocks of 500 item ids\n\nlocal _, SFP = ...\n\n")
    f.write("SFP.TransmogParts = {\n" + "\n".join(index) + "\n}\n")
print("%d blocks in %d folders, %d items" % (len(blocks), len(parts), total))
