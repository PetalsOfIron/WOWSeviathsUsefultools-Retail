"""Bakes the load-on-demand folder SeviathsUsefulTools_Transmog: every transmog item of Wowhead's list (tools/transmog_items.txt) with where it comes from.

Source lines: id|name|quality|source type|source name|class|subclass|slot|level|required level|classes  (read in a browser from https://www.wowhead.com/transmog-items)
Output: Transmog.lua with SeviathsTransmogBlocks[id // 500] = "id|name|quality|source|source name|item class|subclass|slot|required level|classes\n..." - the game reads one block per item looked at.
Run: python tools/bake_transmog.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ADDON = os.path.dirname(HERE)
OUT = os.path.join(os.path.dirname(ADDON), "SeviathsUsefulTools_Transmog")
BLOCK = 500

blocks = {}
for line in open(os.path.join(HERE, "transmog_items.txt"), encoding="utf8").read().splitlines():
    p = line.split("|")
    if len(p) < 5 or not p[0].isdigit():
        continue
    iid = int(p[0])
    p += [""] * (11 - len(p))
    rec = "|".join([p[0], p[1].replace("\\", "").replace('"', "'"), p[2], p[3], p[4].replace("\\", "").replace('"', "'"), p[5], p[6], p[7], p[9], p[10]])
    blocks.setdefault(iid // BLOCK, []).append(rec)

os.makedirs(OUT, exist_ok=True)
with open(os.path.join(OUT, "Transmog.lua"), "w", encoding="utf8", newline="\n") as f:
    f.write("-- generated by tools/bake_transmog.py: Wowhead's transmog items (id|name|quality|source type|source name), %d items\n" % sum(len(v) for v in blocks.values()))
    f.write("SeviathsTransmogBlocks = {\n")
    for b in sorted(blocks):
        f.write('[%d]="%s",\n' % (b, "\\n".join(blocks[b])))
    f.write("}\n")
main_toc = open(os.path.join(ADDON, "SeviathsUsefulTools.toc"), encoding="utf8").read().splitlines()
interface = next((l for l in main_toc if l.startswith("## Interface")), "## Interface: 120100")
with open(os.path.join(OUT, "SeviathsUsefulTools_Transmog.toc"), "w", encoding="utf8", newline="\n") as f:
    f.write("%s\n## Title: SeviathsUsefulTools - transmog items\n## Notes: Where every transmog item comes from, read only when an item is looked at.\n"
            "## Dependencies: SeviathsUsefulTools\n## LoadOnDemand: 1\n## Author: Seviath\n\nTransmog.lua\n" % interface)
print("%d blocks, %.1f MB -> %s" % (len(blocks), os.path.getsize(os.path.join(OUT, "Transmog.lua")) / 1e6, OUT))
