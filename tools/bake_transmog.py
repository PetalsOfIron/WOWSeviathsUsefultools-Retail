"""Bakes the load-on-demand folder SeviathsUsefulTools_Transmog: every transmog item of Wowhead's list (tools/transmog_items.txt) with where it comes from.

Source lines: id|name|quality|source type|source name|class|subclass|slot|level|required level|classes  (read in a browser from https://www.wowhead.com/transmog-items)
Output: Transmog.1.lua, Transmog.2.lua ... (about 1 MB each) filling SeviathsTransmogBlocks[id // 500] = "id|name|quality|source|source name|item class|subclass|slot|required level|classes\n..."
- the game reads one block per item looked at. The .toc lists every part, so no single file gets too big for the game.
Run: python tools/bake_transmog.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ADDON = os.path.dirname(HERE)
OUT = os.path.join(os.path.dirname(ADDON), "SeviathsUsefulTools_Transmog")
BLOCK = 500
MAX_FILE = 1_000_000
BS = chr(92)

blocks = {}
for line in open(os.path.join(HERE, "transmog_items.txt"), encoding="utf8").read().splitlines():
    p = line.split("|")
    if len(p) < 5 or not p[0].isdigit():
        continue
    iid = int(p[0])
    p += [""] * (11 - len(p))
    rec = "|".join([p[0], p[1].replace(BS, "").replace('"', "'"), p[2], p[3], p[4].replace(BS, "").replace('"', "'"), p[5], p[6], p[7], p[9], p[10]])
    blocks.setdefault(iid // BLOCK, []).append(rec)

os.makedirs(OUT, exist_ok=True)
for old in os.listdir(OUT):
    if old.endswith(".lua"):
        os.remove(os.path.join(OUT, old))
parts, cur, size = [], [], 0
for b in sorted(blocks):
    line = 'B[%d]="%s"' % (b, (BS + "n").join(blocks[b]))
    if cur and size + len(line) > MAX_FILE:
        parts.append(cur)
        cur, size = [], 0
    cur.append(line)
    size += len(line) + 1
if cur:
    parts.append(cur)
total = sum(len(v) for v in blocks.values())
names = []
for i, part in enumerate(parts, 1):
    name = "Transmog.%d.lua" % i
    names.append(name)
    with open(os.path.join(OUT, name), "w", encoding="utf8", newline="\n") as f:
        f.write("-- generated by tools/bake_transmog.py: Wowhead's transmog items, part %d of %d (%d items in all)\n" % (i, len(parts), total))
        f.write("SeviathsTransmogBlocks = SeviathsTransmogBlocks or {}\nlocal B = SeviathsTransmogBlocks\n")
        for line in part:
            f.write(line + "\n")
main_toc = open(os.path.join(ADDON, "SeviathsUsefulTools.toc"), encoding="utf8").read().splitlines()
interface = next((l for l in main_toc if l.startswith("## Interface")), "## Interface: 120100")
with open(os.path.join(OUT, "SeviathsUsefulTools_Transmog.toc"), "w", encoding="utf8", newline="\n") as f:
    f.write(interface + "\n## Title: SeviathsUsefulTools - transmog items\n## Notes: Where every transmog item comes from, read only when an item is looked at.\n")
    f.write("## Dependencies: SeviathsUsefulTools\n## LoadOnDemand: 1\n## Author: Seviath\n\n" + "\n".join(names) + "\n")
print("%d blocks in %d files, %d items -> %s" % (len(blocks), len(parts), total, OUT))
